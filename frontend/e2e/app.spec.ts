test('多账号、标签页隔离、延迟响应与单账号退出', async ({ page, context }) => {
  await login(page)
  await page.getByRole('button', { name: '切换儿童账号' }).click()
  await page.getByRole('button', { name: '添加儿童账号', exact: true }).click()
  await page.getByLabel('账号', { exact: true }).fill('e2e-child-two')
  await page.getByLabel('密码', { exact: true }).fill('e2e-only-password-123')
  await page.getByRole('button', { name: '开始今天的小冒险' }).click()
  await expect(page.locator('.account-button')).toContainText('星星')
  await expect(page.getByRole('checkbox')).toHaveCount(0)
  const second = await context.newPage()
  await second.goto('/')
  await expect(second.locator('.account-button')).toContainText('朵朵')
  await expect(page.locator('.account-button')).toContainText('星星')
  await second.route('**/api/v1/me/days/*/prepare', async (route) => {
    await new Promise((resolve) => setTimeout(resolve, 700))
    await route.continue().catch(() => {})
  })
  const pending = second.waitForRequest('**/api/v1/me/days/*/prepare')
  await second.reload()
  await pending
  await second.getByRole('button', { name: '切换儿童账号' }).click()
  await second.getByRole('button', { name: '🐰 星星' }).click()
  await expect(second.locator('.account-button')).toContainText('星星')
  await expect(second.getByRole('checkbox')).toHaveCount(0)
  await second.setViewportSize({ width: 360, height: 800 })
  await second.screenshot({ path: 'test-results/today-mobile.png', fullPage: true })
  expect(await second.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: '切换儿童账号' }).click()
  page.once('dialog', (dialog) => dialog.accept())
  await page.getByRole('button', { name: '退出朵朵' }).click()
  await expect(page.getByRole('button', { name: '退出朵朵' })).toHaveCount(0)
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.locator('.account-button')).toContainText('星星')
  await second.close()
})

test('今日和日历任务在手机、平板首屏可见', async ({ page }) => {
  await login(page)
  for (const viewport of [
    { width: 320, height: 640 },
    { width: 390, height: 844 },
    { width: 768, height: 1024 },
    { width: 1194, height: 834 },
  ]) {
    await page.setViewportSize(viewport)
    await page.goto('/calendar?mode=today')
    const tasks = page.locator('.today-tasks .task-row')
    await expect(tasks.first()).toBeVisible()
    const first = await tasks.first().boundingBox()
    const second = await tasks.nth(1).boundingBox()
    const nav = await page.locator('.mobile-nav').boundingBox()
    expect(first!.y).toBeLessThan(220)
    expect(second!.y + second!.height).toBeLessThan(nav!.y)
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.locator('.today-overview, .reward-strip')).toHaveCount(0)
    await page.screenshot({ path: `test-results/today-first-screen-${viewport.width}.png` })

    await page.getByRole('link', { name: '成长日历', exact: true }).click()
    await expect(page.getByRole('heading', { name: '我的一周' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: '本周', exact: true })).toHaveCount(1)
    await expect(page.locator('.week-navigation button')).toHaveCount(3)
    const calendar = await page.locator('.week-scroll').boundingBox()
    const navigation = await page.locator('.week-navigation').boundingBox()
    expect(navigation!.y).toBeGreaterThanOrEqual(calendar!.y + calendar!.height)
    const cards = page.locator('.week-day-tasks.week-today .week-task-state')
    await expect(cards.first()).toBeVisible()
    const firstCard = await cards.first().boundingBox()
    const secondCard = await cards.nth(1).boundingBox()
    expect(firstCard!.y).toBeLessThan(300)
    expect(secondCard!.y + secondCard!.height).toBeLessThan(nav!.y)
    expect(await page.evaluate(() => window.scrollY)).toBe(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/calendar-first-screen-${viewport.width}.png` })
  }
})

